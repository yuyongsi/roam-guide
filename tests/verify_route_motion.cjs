const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
let count=0;const check=(value,message)=>{assert(value,message);count++;};
const timers=new Map(),scrolls=[],animations=[],attributes={};let timerId=0,focused=0,reducedChange;
const progress={hidden:true},media={matches:false,addEventListener:(type,fn)=>reducedChange=fn};
const main={innerHTML:'old',inert:false,setAttribute:(k,v)=>attributes[k]=v,removeAttribute:k=>delete attributes[k],focus:()=>focused++,animate:(frames,options)=>{
 let finish,reject;const finished=new Promise((a,b)=>{finish=a;reject=b;});
 const animation={frames,options,finished,finish,cancelled:false,cancel(){this.cancelled=true;reject(new Error('cancelled'));}};
 animations.push(animation);return animation;
}};
const c=vm.createContext({document:{getElementById:id=>id==='main'?main:progress},window:{matchMedia:()=>media,scrollTo:p=>scrolls.push(p)},setTimeout:fn=>{timers.set(++timerId,fn);return timerId;},clearTimeout:id=>timers.delete(id)});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/main/resources/static/js/route-motion.js'),'utf8'),c);
const motion=vm.runInContext('routeMotion',c),flush=()=>{const callbacks=[...timers.values()];timers.clear();callbacks.forEach(fn=>fn());};
(async()=>{
 let context=motion.begin(1,'/',undefined);await motion.commit(context,'home');
 check(main.innerHTML==='home'&&!main.inert&&!animations.length,'首次渲染不播放切页动画');
 context=motion.begin(2,'/destinations',0);const firstExit=animations.at(-1);
 check(main.innerHTML==='home'&&main.inert&&attributes['aria-busy']==='true','请求期间保留旧内容并阻止旧内容操作');
 check(progress.hidden,'快速响应不闪进度条');flush();check(!progress.hidden,'慢响应显示加载反馈');
 const staleCommit=motion.commit(context,'stale');
 const newer=motion.begin(3,'/food',0),exit=animations.at(-1),pending=motion.commit(newer,'food');
 check(!await staleCommit&&main.innerHTML==='home'&&firstExit.cancelled,'淡出期间新导航取消旧提交');
 check(main.inert,'淡出完成前不提前替换页面');exit.finish();await pending;
 check(main.innerHTML==='food'&&!main.inert&&!attributes['aria-busy']&&progress.hidden,'完成切换恢复操作并清除加载状态');
 check(scrolls.at(-1).top===0&&scrolls.at(-1).behavior==='instant'&&focused===1,'新内容提交后即时归顶及转移焦点');
 check(animations.at(-1).frames[0].transform==='translateY(24px)'&&animations.at(-1).options.duration===360,'新页面从下方明显移入');
 const enter=animations.at(-1),before=animations.length;
 context=motion.begin(4,'/food',undefined);await motion.commit(context,'saved');
 check(enter.cancelled&&animations.length===before&&scrolls.length===1,'原页刷新取消动画且不改变滚动');
 media.matches=true;context=motion.begin(5,'/guides',840);await motion.commit(context,'guides');
 check(animations.length===before&&scrolls.at(-1).top===840,'减少动态效果时直接切换并恢复阅读位置');
 media.matches=false;context=motion.begin(6,'/routes',0);const interruptedExit=animations.at(-1),reducedPending=motion.commit(context,'routes');
 media.matches=true;reducedChange();await reducedPending;
 check(interruptedExit.cancelled&&main.innerHTML==='routes'&&!main.inert,'中途减少动态效果不会阻塞提交');
 context=motion.begin(7,'/broken',0);flush();await motion.commit(context,'error with retry');flush();
 check(main.innerHTML==='error with retry'&&!main.inert&&progress.hidden&&!attributes['aria-busy'],'错误页面同样释放忙碌状态');
 media.matches=false;delete main.animate;context=motion.begin(8,'/',0);await motion.commit(context,'fallback');
 check(main.innerHTML==='fallback'&&!main.inert,'动效API不可用时正常降级');
 check(!await motion.commit(newer,'late'),'已经过期的上下文始终不能提交');
 console.log('PASS '+count+' route motion assertions');
})().catch(error=>{console.error(error);process.exitCode=1;});
