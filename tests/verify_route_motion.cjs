const fs=require('fs'),vm=require('vm'),assert=require('assert'),path=require('path');
let count=0;const check=(value,message)=>{assert(value,message);count++;};
const timers=new Map(),scrolls=[],animations=[],attributes={};let timerId=0,focused=0,reducedChange;
const progress={hidden:true},media={matches:false,addEventListener:(type,fn)=>reducedChange=fn};
const main={innerHTML:'old',inert:false,setAttribute:(k,v)=>attributes[k]=v,removeAttribute:k=>delete attributes[k],focus:()=>focused++,animate:(frames,options)=>{const a={cancelled:false,cancel(){this.cancelled=true;}};animations.push(a);return a;}};
const c=vm.createContext({document:{getElementById:id=>id==='main'?main:progress},window:{matchMedia:()=>media,scrollTo:p=>scrolls.push(p)},setTimeout:fn=>{timers.set(++timerId,fn);return timerId;},clearTimeout:id=>timers.delete(id)});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../src/main/resources/static/js/route-motion.js'),'utf8'),c);
const motion=vm.runInContext('routeMotion',c),flush=()=>{const callbacks=[...timers.values()];timers.clear();callbacks.forEach(fn=>fn());};
let context=motion.begin(1,'/',undefined);motion.commit(context,'home');
check(main.innerHTML==='home'&&!main.inert&&!animations.length,'首次渲染不播放切页动画');
context=motion.begin(2,'/destinations',0);
check(main.innerHTML==='home'&&main.inert&&attributes['aria-busy']==='true','请求期间保留旧内容并阻止旧内容操作');
check(progress.hidden,'快速响应不闪进度条');flush();check(!progress.hidden,'慢响应显示加载反馈');
const newer=motion.begin(3,'/food',0);
check(!motion.commit(context,'stale')&&main.innerHTML==='home','迟到响应不得覆盖新路由');
motion.commit(newer,'food');
check(main.innerHTML==='food'&&!main.inert&&!attributes['aria-busy']&&progress.hidden,'完成切换恢复操作并清除加载状态');
check(scrolls.at(-1).top===0&&scrolls.at(-1).behavior==='instant'&&focused===1,'新内容提交后即时归顶及转移焦点');
check(animations.length===1,'路由变化播放轻淡入');
context=motion.begin(4,'/food',undefined);check(animations[0].cancelled,'新请求取消旧动画');motion.commit(context,'saved');
check(animations.length===1&&scrolls.length===1,'原页保存刷新不动画也不改变滚动');
media.matches=true;context=motion.begin(5,'/guides',840);motion.commit(context,'guides');
check(animations.length===1&&scrolls.at(-1).top===840,'减少动态效果时直接切换并恢复阅读位置');
media.matches=false;context=motion.begin(6,'/routes',0);motion.commit(context,'routes');media.matches=true;reducedChange();
check(animations.at(-1).cancelled,'切换系统偏好立即停止动画');
context=motion.begin(7,'/broken',0);flush();motion.commit(context,'error with retry');flush();
check(main.innerHTML==='error with retry'&&!main.inert&&progress.hidden&&!attributes['aria-busy'],'错误页面同样释放忙碌状态');
// 不支持 Web Animations 的浏览器仍可正常提交页面。
media.matches=false;delete main.animate;context=motion.begin(8,'/',0);motion.commit(context,'fallback');
check(main.innerHTML==='fallback'&&!main.inert,'动效API不可用时正常降级');
console.log('PASS '+count+' route motion assertions');
